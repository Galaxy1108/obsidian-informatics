int cacl(int m)
{
    for (int i = 1; i <= n; i++) b[i] = a[i];
    int cnt, lst = -1, l = 1, r = n;
    while (1)
    {
        cnt = 0;
        for (int i = l; i <= r; i++)
        {
            cnt += !b[i];
            if (i > l && !cnt) l = i;
            if (!b[i] && cnt % m == 1) b[i] = 1, lst = i;
        }
        if (!cnt) return lst;
        cnt = 0;
        for (int i = r; i >= l; i--)
        {
            cnt += !b[i];
            if (i < r && !cnt) r = i;
            if (!b[i] && cnt % m == 1) b[i] = 1, lst = i;
        }
        if (!cnt) return lst;
    }
}

